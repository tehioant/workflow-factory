use ts_rs::TS;
use workflow_engine::runtime::{IsolationEvidence, Readiness, RuntimeStatus, SetupPlan};
use workflow_engine::{
    AiBlock, AuthReadiness, CodexConfiguration, Definition, Error, GraphConnection, Position,
    PreparedInputs, Reasoning, SaveConfiguration, SaveDefinition, SavedConfiguration,
    SavedDefinition, WorkflowInput,
};
fn main() {
    let config = Default::default();
    let declarations = [
        Readiness::decl(&config),
        RuntimeStatus::decl(&config),
        IsolationEvidence::decl(&config),
        SetupPlan::decl(&config),
        Position::decl(&config),
        AiBlock::decl(&config),
        GraphConnection::decl(&config),
        WorkflowInput::decl(&config),
        PreparedInputs::decl(&config),
        CodexConfiguration::decl(&config),
        Reasoning::decl(&config),
        SavedConfiguration::decl(&config),
        SaveConfiguration::decl(&config),
        AuthReadiness::decl(&config),
        Definition::decl(&config),
        SavedDefinition::decl(&config),
        SaveDefinition::decl(&config),
        Error::decl(&config),
    ];
    let output = format!(
        "// Generated by cargo run -p workflow-engine --bin export-types. Do not edit.\n{}\n",
        declarations.join("\n").replace("type ", "export type ")
    );
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/lib/transport.ts");
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    if std::env::args().any(|arg| arg == "--check") {
        assert_eq!(
            std::fs::read_to_string(path).unwrap(),
            output,
            "Generated transport is stale; run npm run types"
        );
    } else {
        std::fs::write(path, output).unwrap();
    }
}
