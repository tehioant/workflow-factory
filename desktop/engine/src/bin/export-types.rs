use ts_rs::TS;
use workflow_engine::{
    AiBlock, Definition, Error, GraphConnection, Position, PreparedInputs, SaveDefinition,
    SavedDefinition, WorkflowInput,
};
fn main() {
    let output = format!("// Generated by cargo run -p workflow-engine --bin export-types. Do not edit.\n{}\n{}\n{}\n{}\n", Definition::decl(&Default::default()), SavedDefinition::decl(&Default::default()), SaveDefinition::decl(&Default::default()), Error::decl(&Default::default()));
    let output = format!(
        "{}\n{}\n{}",
        WorkflowInput::decl(&Default::default()),
        PreparedInputs::decl(&Default::default()),
        output
    );
    let output = format!(
        "{}\n{}\n{}\n{}\n{}\n{}",
        workflow_engine::CodexConfiguration::decl(&Default::default()),
        workflow_engine::Reasoning::decl(&Default::default()),
        workflow_engine::SavedConfiguration::decl(&Default::default()),
        workflow_engine::SaveConfiguration::decl(&Default::default()),
        workflow_engine::AuthReadiness::decl(&Default::default()),
        output
    );
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/lib/transport.ts");
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    let output = format!(
        "{}\n{}\n{}\n{}",
        Position::decl(&Default::default()),
        AiBlock::decl(&Default::default()),
        GraphConnection::decl(&Default::default()),
        output
    )
    .replace("type ", "export type ");
    if std::env::args().any(|arg| arg == "--check") {
        assert_eq!(
            std::fs::read_to_string(path).unwrap(),
            output,
            "Generated transport is stale; run npm run types"
        );
    } else {
        std::fs::write(path, output).unwrap();
    }
}
